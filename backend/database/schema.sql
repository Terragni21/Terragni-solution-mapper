-- ============================================================
-- Terragni Solution Mapper - PostgreSQL / Supabase schema
-- ============================================================
-- Safe to run more than once (IF NOT EXISTS everywhere).
-- Table and column names are unquoted lower-case so that both the
-- new code (lower-case) and the old Oracle-style code (UPPER-CASE,
-- unquoted) refer to the same objects.
--
-- Run it with:  python -m backend.database.migrate_to_supabase
-- or paste it into Supabase -> SQL Editor.
-- ============================================================

-- ---------- Source documents --------------------------------
CREATE TABLE IF NOT EXISTS document (
    document_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             TEXT,
    file_name         TEXT,
    file_type         TEXT,
    client_name       TEXT,
    description       TEXT,
    version_label     TEXT,
    status            TEXT DEFAULT 'ACTIVE',
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    document_type     TEXT,
    source_path       TEXT,
    file_hash         TEXT,
    ingestion_status  TEXT
);

CREATE TABLE IF NOT EXISTS document_section (
    section_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id    BIGINT REFERENCES document(document_id) ON DELETE CASCADE,
    section_type   TEXT,
    page_number    INTEGER,
    slide_number   INTEGER,
    section_title  TEXT,
    text_content   TEXT,
    section_order  INTEGER,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document_chunk (
    chunk_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id  BIGINT REFERENCES document(document_id) ON DELETE CASCADE,
    section_id   BIGINT REFERENCES document_section(section_id) ON DELETE SET NULL,
    chunk_text   TEXT,
    chunk_order  INTEGER,
    token_count  INTEGER,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS document_chunk_embedding (
    embedding_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chunk_id        BIGINT NOT NULL REFERENCES document_chunk(chunk_id) ON DELETE CASCADE,
    model_name      TEXT NOT NULL,
    dimensions      INTEGER,
    embedding_json  TEXT NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (chunk_id, model_name)
);

-- ---------- Master knowledge --------------------------------
CREATE TABLE IF NOT EXISTS industry (
    industry_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    industry_code  TEXT,
    industry_name  TEXT,
    description    TEXT,
    status         TEXT DEFAULT 'ACTIVE',
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS offering (
    offering_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_code  TEXT,
    offering_name  TEXT,
    description    TEXT,
    status         TEXT DEFAULT 'ACTIVE',
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS framework (
    framework_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    framework_code  TEXT,
    framework_name  TEXT,
    description     TEXT,
    status          TEXT DEFAULT 'ACTIVE',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS challenge (
    challenge_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_code  TEXT,
    challenge_name  TEXT,
    description     TEXT,
    status          TEXT DEFAULT 'ACTIVE',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS outcome (
    outcome_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outcome_code  TEXT,
    outcome_name  TEXT,
    description   TEXT,
    status        TEXT DEFAULT 'ACTIVE',
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS case_study (
    case_study_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_study_code   TEXT,
    title             TEXT,
    client_name       TEXT,
    public_title      TEXT,
    summary           TEXT,
    challenge         TEXT,
    objective         TEXT,
    approach          TEXT,
    key_finding       TEXT,
    solution          TEXT,
    business_outcome  TEXT,
    status            TEXT DEFAULT 'ACTIVE',
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Case-study relationships ------------------------
CREATE TABLE IF NOT EXISTS case_study_industry (
    case_study_id      BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    industry_id        BIGINT REFERENCES industry(industry_id) ON DELETE CASCADE,
    relationship_type  TEXT,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, industry_id)
);

CREATE TABLE IF NOT EXISTS case_study_offering (
    case_study_id      BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    offering_id        BIGINT REFERENCES offering(offering_id) ON DELETE CASCADE,
    relationship_type  TEXT,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, offering_id)
);

CREATE TABLE IF NOT EXISTS case_study_framework (
    case_study_id      BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    framework_id       BIGINT REFERENCES framework(framework_id) ON DELETE CASCADE,
    relationship_type  TEXT,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, framework_id)
);

CREATE TABLE IF NOT EXISTS case_study_challenge (
    case_study_id      BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    challenge_id       BIGINT REFERENCES challenge(challenge_id) ON DELETE CASCADE,
    relationship_type  TEXT,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, challenge_id)
);

CREATE TABLE IF NOT EXISTS case_study_outcome (
    case_study_id      BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    outcome_id         BIGINT REFERENCES outcome(outcome_id) ON DELETE CASCADE,
    relationship_type  TEXT,
    created_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, outcome_id)
);

CREATE TABLE IF NOT EXISTS case_study_evidence (
    case_study_id   BIGINT REFERENCES case_study(case_study_id) ON DELETE CASCADE,
    chunk_id        BIGINT REFERENCES document_chunk(chunk_id) ON DELETE CASCADE,
    evidence_type   TEXT,
    relevance_note  TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (case_study_id, chunk_id)
);

-- ---------- Knowledge pipeline staging ----------------------
CREATE TABLE IF NOT EXISTS knowledge_extraction_staging (
    staging_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id         BIGINT,
    chunk_id            BIGINT,
    entity_type         TEXT,
    entity_name         TEXT,
    entity_code         TEXT,
    relationship_type   TEXT,
    extracted_text      TEXT,
    confidence_score    NUMERIC,
    extraction_status   TEXT DEFAULT 'PENDING',
    review_notes        TEXT,
    parent_entity_type  TEXT,
    parent_entity_name  TEXT,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Website leads and question log ------------------
CREATE TABLE IF NOT EXISTS user_leads (
    reference           TEXT PRIMARY KEY,
    submitted_at        TEXT,
    name                TEXT,
    email               TEXT,
    organisation        TEXT,
    phone               TEXT,
    message             TEXT,
    industry            TEXT,
    role                TEXT,
    question            TEXT,
    summary             TEXT,
    suggested_services  TEXT,
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_queries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logged_at   TEXT,
    industry    TEXT,
    role        TEXT,
    path        TEXT,
    outcome     TEXT,
    query_text  TEXT,
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Helpful indexes ---------------------------------
CREATE INDEX IF NOT EXISTS ix_chunk_document      ON document_chunk (document_id);
CREATE INDEX IF NOT EXISTS ix_section_document    ON document_section (document_id);
CREATE INDEX IF NOT EXISTS ix_embedding_model     ON document_chunk_embedding (model_name);
CREATE INDEX IF NOT EXISTS ix_evidence_chunk      ON case_study_evidence (chunk_id);
CREATE INDEX IF NOT EXISTS ix_document_file_hash  ON document (file_hash);
CREATE INDEX IF NOT EXISTS ix_staging_status      ON knowledge_extraction_staging (extraction_status);
